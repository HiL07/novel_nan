def build(output: Path) -> None:
    doc = Document()
    doc.core_properties.title = BOOK_TITLE
    for title, paras in CHAPTERS.items():
        h = doc.add_heading(title, level=1)
        for r in h.runs:
            r.font.size = Pt(16)
        for p in paras:
            doc.add_paragraph(p)
    doc.save(str(output))
    print(f"fixture written: {output} ({sum(len(v) for v in CHAPTERS.values())} paras)")


